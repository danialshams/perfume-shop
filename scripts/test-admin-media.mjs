import assert from "node:assert/strict";
import {validateMediaBytes,validateMediaMeta,IMAGE_MAX_BYTES,VOICE_MAX_BYTES} from "../lib/admin-media-validation.ts";
const meta=(name,size,type="")=>({name,size,type});
const b=(header)=>Uint8Array.from([...header,...new Array(20).fill(0)]);
const good=(r)=>assert.equal(r.ok,true,JSON.stringify(r));
const bad=(r)=>assert.equal(r.ok,false,JSON.stringify(r));
good(validateMediaMeta(meta("photo.jpg",IMAGE_MAX_BYTES,"image/jpeg"),"image"));
bad(validateMediaMeta(meta("photo.jpg",IMAGE_MAX_BYTES+1,"image/jpeg"),"image"));
bad(validateMediaMeta(meta("voice.mp3",VOICE_MAX_BYTES+1,"audio/mpeg"),"voice"));
good(validateMediaMeta(meta("voice.mp3",VOICE_MAX_BYTES,"audio/mpeg"),"voice"));
bad(validateMediaMeta(meta("voice.mp3",0,"audio/mpeg"),"voice"));
bad(validateMediaMeta(meta("voice.exe",1024,"audio/mpeg"),"voice"));
bad(validateMediaMeta(meta("voice.mp3",1024,"image/png"),"voice"));
bad(validateMediaMeta(meta("photo.png",1024,"audio/mpeg"),"image"));
good(validateMediaBytes(meta("photo.jpg",1024,"image/jpeg"),"image",b([255,216,255,224])));
bad(validateMediaBytes(meta("photo.jpg",1024,"image/jpeg"),"image",b([60,104,116,109,108])));
good(validateMediaBytes(meta("clip.mp3",1024,"audio/mpeg"),"voice",b([73,68,51,4])));
bad(validateMediaBytes(meta("clip.mp3",1024,"audio/mpeg"),"voice",b([0,0,0,0])));
good(validateMediaBytes(meta("photo.webp",1024,"image/webp"),"image",b([82,73,70,70,0,0,0,0,87,69,66,80])));
good(validateMediaBytes(meta("clip.wav",1024,"audio/wav"),"voice",b([82,73,70,70,0,0,0,0,87,65,86,69])));
console.log("Image/audio MIME, content signatures, zero bytes and 5/20 MB boundaries passed.");
